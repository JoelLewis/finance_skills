@given(amount, rate, st.integers(1, 480))
def test_annuity_pv_equals_sum_of_discounted_payments(pmt, r, n):
    direct = sum(pmt / (1 + r) ** t for t in range(1, n + 1))
    assert close(TVM.annuity_pv(pmt, r, n), direct, rel=1e-9)
    assert close(TVM.annuity_pv(pmt, r, n, due=True), direct * (1 + r), rel=1e-9)


@given(amount, rate, st.integers(1, 480))
def test_annuity_fv_is_pv_compounded(pmt, r, n):
    assert close(TVM.annuity_fv(pmt, r, n),
                 TVM.annuity_pv(pmt, r, n) * (1 + r) ** n, rel=1e-9)


@given(amount, st.floats(-0.5, 0.5), st.integers(0, 100))
def test_pv_and_fv_are_inverses(x, r, n):
    assert close(TVM.present_value(TVM.future_value(x, r, n), r, n), x, rel=1e-9)


@given(st.floats(1_000, 2_000_000), st.floats(0.0, 0.20), st.integers(1, 480))
def test_amortization_pays_off_exactly(principal, annual_rate, n):
    loan = tvm.AmortizationSchedule(principal, annual_rate, n)
    rows = loan.schedule()
    assert len(rows) == n
    assert rows[-1]["remaining_balance"] == 0.0
    balances = [principal] + [row["remaining_balance"] for row in rows]
    assert all(b1 <= b0 + 0.01 for b0, b1 in zip(balances, balances[1:]))
    # Principal repaid equals the loan, up to cent rounding on each row.
    repaid = sum(row["principal_payment"] for row in rows)
    assert abs(repaid - principal) <= 0.005 * n + 0.01
    # Every payment but the last is the level payment.
    level = round(loan._compute_payment(), 2)
    assert all(row["payment"] == level for row in rows[:-1])


@given(st.floats(0.0, 1e-6), amount, st.integers(1, 480))
def test_annuities_near_zero_rate_approach_undiscounted_sum(r, pmt, n):
    assert close(TVM.annuity_pv(pmt, r, n), pmt * n, rel=1e-3)
    assert close(TVM.annuity_fv(pmt, r, n), pmt * n, rel=1e-3)


# Conventional cash flows (one outlay, then inflows) have exactly one IRR
# above -100%, including for losing investments.
conventional_cash_flows = st.tuples(
    st.floats(1_000, 1e6), st.lists(st.floats(1, 1e6), min_size=1, max_size=30),
).map(lambda t: [-t[0]] + t[1])


@given(conventional_cash_flows)
def test_irr_sets_npv_to_zero(cash_flows):
    irr = TVM.irr(cash_flows)
    assert irr > -1
    assert abs(TVM.npv(irr, cash_flows)) <= 1e-6 * sum(abs(cf) for cf in cash_flows)


