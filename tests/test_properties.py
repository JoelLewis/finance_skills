bond_terms = st.tuples(
    st.floats(0.0, 0.15),                 # coupon rate
    st.integers(1, 60).map(lambda h: h / 2),  # maturity in years, half-year steps
    st.sampled_from([1, 2, 4, 12]),       # payments per year
)
yield_ = st.floats(0.0001, 0.20)


@given(bond_terms, yield_, yield_)
def test_bond_price_falls_as_yield_rises(terms, y1, y2):
    assume(abs(y1 - y2) > 1e-6)
    lo, hi = sorted((y1, y2))
    bond = sovereign.SovereignBond(1000, *terms)
    assume(bond.n_periods >= 1)
    assert bond.price(hi) < bond.price(lo)


@given(st.floats(0.001, 0.15), st.integers(1, 60).map(lambda h: h / 2),
       st.sampled_from([1, 2, 4, 12]))
def test_bond_prices_at_par_when_coupon_equals_yield(c, maturity, freq):
    bond = sovereign.SovereignBond(1000, c, maturity, freq)
    assume(bond.n_periods >= 1)
    assert close(bond.price(c), 1000.0, rel=1e-9)


@given(bond_terms, yield_)
def test_modified_duration_is_price_sensitivity(terms, y):
    bond = sovereign.SovereignBond(1000, *terms)
    assume(bond.n_periods >= 1)
    h = 1e-6
    slope = (bond.price(y + h) - bond.price(y - h)) / (2 * h)
    assert close(bond.modified_duration(y), -slope / bond.price(y), rel=1e-5)


@given(bond_terms, yield_)
def test_macaulay_duration_within_maturity(terms, y):
    bond = sovereign.SovereignBond(1000, *terms)
    assume(bond.n_periods >= 1)
    d = bond.macaulay_duration(y)
    assert 0 < d <= bond.n_periods / bond.frequency + 1e-12


