# retirement-decumulation (rules as of 2026)
# ---------------------------------------------------------------------------

claim_months = st.integers(62 * 12, 70 * 12)


@given(claim_months, claim_months)
def test_ss_factor_rises_with_claim_age(m1, m2):
    lo, hi = sorted((m1, m2))
    assert RD.ss_claiming_factor(lo / 12) <= RD.ss_claiming_factor(hi / 12)


def test_ss_factor_anchor_points():
    # FRA 67 (born 1960 or later): 70% at 62, 100% at 67, 124% at 70.
    assert close(RD.ss_claiming_factor(62), 0.70)
    assert close(RD.ss_claiming_factor(67), 1.00)
    assert close(RD.ss_claiming_factor(70), 1.24)
    assert close(RD.ss_claiming_factor(72), 1.24)  # no credits past 70


@given(st.floats(500, 5000), claim_months, claim_months)
def test_ss_breakeven_equalizes_cumulative_benefits(pia, m1, m2):
    assume(m1 != m2)
    early, late = sorted((m1 / 12, m2 / 12))
    b_early = RD.ss_monthly_benefit(pia, early)
    b_late = RD.ss_monthly_benefit(pia, late)
    age = RD.ss_breakeven_age(early, b_early, late, b_late)
    assert close(b_early * (age - early) * 12, b_late * (age - late) * 12, rel=1e-9)


def test_rmd_divisor_falls_with_age():
    ages = sorted(decumulation.UNIFORM_LIFETIME_TABLE)
    divisors = [RD.uniform_lifetime_divisor(a) for a in ages]
    assert all(d1 < d0 for d0, d1 in zip(divisors, divisors[1:]))


@given(st.floats(0, 1e8), st.integers(73, 99))
def test_rmd_share_rises_with_age(balance, age):
    assert RD.rmd(balance, RD.uniform_lifetime_divisor(age)) <= RD.rmd(
        balance, RD.uniform_lifetime_divisor(age + 1)) + 1e-9
