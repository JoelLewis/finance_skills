"""Property-based tests for the skill scripts.

Each test states an identity or rule that must hold for every valid input,
then checks it on random inputs generated by Hypothesis. A failing case is
shrunk to the smallest input that breaks the property.
"""

import math

import numpy as np
from hypothesis import assume, given
from hypothesis import strategies as st

from conftest import load_script

attribution = load_script("performance-attribution")
tvm = load_script("time-value-of-money")
returns = load_script("return-calculations")
sovereign = load_script("fixed-income-sovereign")
decumulation = load_script("retirement-decumulation")

TVM = tvm.TimeValueOfMoney
Returns = returns.Returns
RD = decumulation.RetirementDecumulation

# ---------------------------------------------------------------------------
# Strategies
# ---------------------------------------------------------------------------

period_return = st.floats(-0.5, 0.5, allow_nan=False)
rate = st.floats(0.0001, 0.25, allow_nan=False)
amount = st.floats(1.0, 1e7, allow_nan=False)


def close(a: float, b: float, rel: float = 1e-9, abs_: float = 1e-9) -> bool:
    return math.isclose(a, b, rel_tol=rel, abs_tol=abs_)


@st.composite
def weights(draw, n: int) -> np.ndarray:
    """Non-negative weights that sum to 1."""
    raw = np.array(draw(st.lists(st.floats(0.01, 1.0), min_size=n, max_size=n)))
    return raw / raw.sum()


@st.composite
def sector_inputs(draw):
    n = draw(st.integers(1, 12))
    w_p = draw(weights(n))
    w_b = draw(weights(n))
    r_p = np.array(draw(st.lists(period_return, min_size=n, max_size=n)))
    r_b = np.array(draw(st.lists(period_return, min_size=n, max_size=n)))
    return w_p, w_b, r_p, r_b


# ---------------------------------------------------------------------------
# performance-attribution
# ---------------------------------------------------------------------------

@given(sector_inputs())
def test_brinson_effects_sum_to_active_return(inputs):
    bf = attribution.BrinsonFachler(*inputs)
    total = (bf.allocation_effects().sum() + bf.selection_effects().sum()
             + bf.interaction_effects().sum())
    assert close(total, bf.total_active_return(), abs_=1e-12)


@given(st.data(), st.integers(1, 12))
def test_carino_linked_effects_sum_to_cumulative_active(data, n):
    r_p = np.array(data.draw(st.lists(period_return, min_size=n, max_size=n)))
    r_b = np.array(data.draw(st.lists(period_return, min_size=n, max_size=n)))
    active = r_p - r_b
    # Split each period's active return into allocation / selection /
    # interaction in arbitrary proportions.
    a_share = np.array(data.draw(st.lists(st.floats(-2, 2), min_size=n, max_size=n)))
    s_share = np.array(data.draw(st.lists(st.floats(-2, 2), min_size=n, max_size=n)))
    alloc, select = active * a_share, active * s_share
    interact = active - alloc - select

    linker = attribution.MultiPeriodLinker(r_p, r_b, alloc, select, interact)
    result = linker.carino_link()
    expected = float(np.prod(1 + r_p) - np.prod(1 + r_b))
    assert close(result["sum_of_linked_effects"], expected, rel=1e-8, abs_=1e-10)
    assert close(result["cumulative_active_return"], expected, abs_=1e-12)


