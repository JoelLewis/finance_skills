@given(st.lists(period_return, min_size=1, max_size=40),
       st.lists(period_return, min_size=1, max_size=40))
def test_linking_is_associative(first, second):
    whole = Returns.link_returns(first + second)
    parts = (1 + Returns.link_returns(first)) * (1 + Returns.link_returns(second)) - 1
    assert close(whole, parts, abs_=1e-12)
    assert close(Returns.time_weighted_return(first + second), whole, abs_=1e-15)


@given(conventional_cash_flows)
def test_money_weighted_return_matches_irr(cash_flows):
    mwr = Returns.money_weighted_return(list(enumerate(cash_flows)))
    assert close(mwr, TVM.irr(cash_flows), rel=1e-6, abs_=1e-8)


@given(st.lists(period_return, min_size=1, max_size=60))
def test_geometric_mean_not_above_arithmetic_mean(rets):
    assert Returns.geometric_mean(rets) <= Returns.arithmetic_mean(rets) + 1e-12


@given(st.floats(-0.99, 10.0))
def test_simple_and_log_returns_round_trip(r):
    assert close(Returns.log_to_simple(Returns.simple_to_log(r)), r, abs_=1e-12)


# Ranges stay realistic: extreme short-period losses annualize to within
# float precision of -100%, where no formula can round-trip.
@given(amount, st.floats(0.1, 100.0), st.floats(1.0, 50.0))
def test_cagr_compounds_back_to_end_value(begin, growth, years):
    end = begin * growth
    g = Returns.cagr(begin, end, years)
    assert close(begin * (1 + g) ** years, end, rel=1e-9)


@given(st.floats(-0.5, 5.0), st.integers(1, 1000), st.sampled_from([4, 12, 52, 252]))
def test_annualize_matches_compounding(total, periods, per_year):
    assume(periods >= per_year / 4)  # at least a quarter of a year
    annual = Returns.annualize(total, periods, per_year)
    assert close((1 + annual) ** (periods / per_year) - 1, total, rel=1e-9, abs_=1e-12)


